function result=vesselGeometryTable(geometry)
% Independent extension table, preserving existing DSAP exporter field names.
assert(isstruct(geometry)&&isscalar(geometry),'DSAP:GeometryExport','Expected one geometry struct.');
name='Vessel';unit='';if isfield(geometry,'SegmentName'),name=geometry.SegmentName;end
if isfield(geometry,'CurvatureUnits'),unit=geometry.CurvatureUnits;end
result=table(string(name),geometry.Length_px,geometry.Length_mm,geometry.ChordLength_px,geometry.ChordLength_mm, ...
 geometry.DistanceMetric,geometry.ESCAPE_Tortuosity,geometry.MeanCurvature,geometry.MedianCurvature,geometry.MaxCurvature, ...
 geometry.RMSCurvature,geometry.P90Curvature,geometry.P95Curvature,geometry.TotalAbsoluteCurvature,geometry.InflectionCount, ...
 geometry.VTI,geometry.VTI_SDTheta,geometry.VTI_MeanDM,geometry.VTI_NumCriticalPoints,geometry.Valid,geometry.VTIValid,string(unit),string(geometry.Warning), ...
 'VariableNames',{'SegmentName','Length_px','Length_mm','Chord_px','Chord_mm','DistanceMetric','ESCAPE_Tortuosity', ...
 'MeanCurvature','MedianCurvature','MaxCurvature','RMSCurvature','P90Curvature','P95Curvature','TotalAbsoluteCurvature','InflectionCount', ...
 'VTI','VTI_SDTheta','VTI_MeanDM','VTI_NumCriticalPoints','Valid','VTIValid','CurvatureUnits','Warning'});
end
