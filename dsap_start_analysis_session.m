function state=dsap_start_analysis_session(r,source,cache,numerical_valid,raw_products,full_cave,view,folder)
    state=struct('Id',cache.Id,'Revision',0,'SavedRevision',0,'Source',source, ...
        'Cache',cache,'NumericalValid',numerical_valid,'RawProducts',raw_products,'FullCAVE',full_cave, ...
        'Result',r,'View',view,'BaseFolder',folder,'OutputDirectory',folder,'Status','valid');
    state.UpstreamSignature=dsap_analysis_upstream(r,source);
    state.CodeSignature=dsap_analysis_code_signature;
    names={'Source','Preprocessing','Timing','AIF','Quality','CAVE','Deconvolution', ...
        'ParameterMaps','ROIMasks','Curves','Statistics','Presentation'};
    % References specify ownership explicitly; never duplicate volume payload per node.
    references={'Source','Cache.enhanced/native + Result.settings','Result.time_seconds/original_time_seconds', ...
        'Result.aif_mask/aif_curve','Result.signal_quality_features','FullCAVE + Result.vessel_features', ...
        'RawProducts + Cache.irf/filtered','Result.CBF/CBV/Tmax/MTT','Result.roi_masks/partition_stats', ...
        'Result.*tics/roi_irfs','Result.summary_table','View'};
    for k=1:numel(names)
        state.Nodes.(names{k})=struct('ValueReference',references{k}, ...
            'Signature',dsap_analysis_signature({names{k},state.UpstreamSignature,state.CodeSignature}), ...
            'Status','valid','InvalidReason','','Revision',0);
    end
    dsap_analysis_session('install',state);dsap_bind_analysis_controls(state);
end
