function result=dsap_cave_vessel_rois(features,final_mask,nonfinite,aif)
% Keep AV projection overlap explicit; never guess labels for manual additions.
    geometry={logical(features.ArteryMask)&final_mask;logical(features.VeinMask)&final_mask};
    masks=cellfun(@(m)m&~nonfinite,geometry,'UniformOutput',false);
    result=struct('Names',{{'CAVE_Artery';'CAVE_Vein'}}, ...
        'Types',{{'CAVEArtery';'CAVEVein'}},'GeometryMasks',{geometry},'Masks',{masks}, ...
        'OverlapMask',geometry{1}&geometry{2}, ...
        'UnclassifiedMask',final_mask&~(geometry{1}|geometry{2}), ...
        'AIFOverlapPixels',[nnz(masks{1}&aif);nnz(masks{2}&aif)], ...
        'Definition','current CAVE class intersect reviewed vessel exclusion; finite TIC pixels; AIF overlap retained', ...
        'OverlapPolicy','AV projection overlap belongs to both labelled ROIs; never added to tissue union', ...
        'ParameterInterpretation','relative deconvolution descriptors in vessel projections; not tissue perfusion measurements');
end
