function dsap_validate_roi_snapshot(snapshot,source_identity)
% Validate frozen content, including provenance, dtype and pixel order.
    assert(isscalar(snapshot)&&snapshot.SchemaVersion==1&&isequal(snapshot.Confirmed,true), ...
        'DSAP:SnapshotInvalid','A confirmed v1 Snapshot is required.');
    assert(strcmp(snapshot.FullSignature,dsap_analysis_signature(rmfield(snapshot,'FullSignature'))), ...
        'DSAP:SnapshotChanged','Frozen Snapshot content has changed.');
    sha=snapshot.SourceIdentity.SHA256;
    assert(ischar(sha)&&~isempty(regexp(sha,'^[0-9a-f]{64}$','once')), ...
        'DSAP:SnapshotSource','Content SHA-256 is required.');
    if nargin>1
        assert(strcmp(sha,source_identity.SHA256)&&snapshot.SourceIdentity.Bytes==source_identity.Bytes, ...
            'DSAP:SnapshotSourceChanged','Source content differs from the frozen Snapshot.');
    end
    size_expected=snapshot.Geometry.ImageSize;
    geometry=rmfield(snapshot.Geometry,'ID');
    assert(strcmp(snapshot.Geometry.ID,dsap_analysis_signature(geometry)), ...
        'DSAP:SnapshotGeometry','Geometry signature differs.');
    assert(isequal(size_expected,size(snapshot.AnalysisScope.BandMask))&& ...
        islogical(snapshot.AnalysisScope.BandMask)&&islogical(snapshot.AnalysisScope.Mask)&& ...
        isequal(size(snapshot.AnalysisScope.Mask),size_expected), ...
        'DSAP:SnapshotGeometry','Scope dimensions or dtype differ.');
    rois=snapshot.ROIs;ids={rois.ID};
    assert(numel(unique(ids))==numel(ids)&&nnz(strcmp({rois.Role},'AIF'))==1, ...
        'DSAP:SnapshotRoles','Unique IDs and exactly one AIF are required.');
    for k=1:numel(rois)
        assert(islogical(rois(k).Mask)&&isequal(size(rois(k).Mask),size_expected)&& ...
            strcmp(rois(k).GeometryID,snapshot.Geometry.ID)&&strcmp(rois(k).SourceIdentityID,sha), ...
            'DSAP:SnapshotGeometry','ROI mask, geometry or source identity differs.');
    end
    assert(all(ismember(snapshot.StatisticsPlan.ROIIds,ids)), ...
        'DSAP:SnapshotRows','StatisticsPlan references a missing ROI.');
    plan=snapshot.StatisticsPlan;
    assert(numel(unique(plan.ROIIds))==numel(plan.ROIIds)&&numel(plan.ROIIds)==numel(plan.Names), ...
        'DSAP:SnapshotRows','Statistics rows must be unique and ordered.');
    if strcmp(plan.Version,'partition-v1')
        assert(numel(plan.ROIIds)==3&&~plan.ClipToCranialBand&&~plan.AppendUnion&& ...
            plan.MinimumTICPixels==0&&strcmp(plan.CoverageDenominator,'max(TICPixels,1)')&& ...
            ~plan.IncludeOuterMaskField,'DSAP:SnapshotPolicy','Invalid partition statistics policy.');
    elseif strcmp(plan.Version,'native-freehand-v1')
        assert(~isempty(plan.ROIIds)&&all(startsWith(plan.ROIIds,'Tissue'))&& ...
            ~plan.ClipToCranialBand&&~plan.AppendUnion&&plan.MinimumTICPixels==3&& ...
            strcmp(plan.CoverageDenominator,'TICPixels')&&~plan.IncludeOuterMaskField, ...
            'DSAP:SnapshotPolicy','Invalid native freehand statistics policy.');
    elseif strcmp(plan.Version,'imported-v1')
        assert(plan.ClipToCranialBand&&plan.AppendUnion==(numel(plan.ROIIds)>1)&& ...
            plan.MinimumTICPixels==3&&strcmp(plan.CoverageDenominator,'TICPixels')&& ...
            plan.IncludeOuterMaskField&&strcmp(plan.UnionName,'TIMESlice_合并'), ...
            'DSAP:SnapshotPolicy','Invalid imported statistics policy.');
    else
        error('DSAP:SnapshotPolicy','Unknown statistics policy.');
    end
end
