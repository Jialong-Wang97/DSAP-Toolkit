function contract=dsap_verify_timeslice_orientation(fixtures,version,audit_file)
% Mint a contract only from real reviewed v2 bundles, never from raw masks.
    assert(nargin>=2&&iscell(fixtures)&&numel(fixtures)>=3, ...
        'DSAP:OrientationEvidenceMissing','At least three reviewed real fixture MAT paths are required.');
    assert(strlength(string(version))>0,'DSAP:OrientationVersion','Explicit contract version is required.');
    assert(nargin==3&&isfile(audit_file),'DSAP:OrientationProfileAudit','A complete observable-profile audit is required.');
    audit=jsondecode(fileread(audit_file));profile_key='';header_profile=[];
    assert(audit.counts.Step==numel(audit.records)+numel(audit.exceptions), ...
        'DSAP:OrientationProfileAudit','Audit does not account for every historical/current Step.');
    evidence=cell(numel(fixtures),1);positions=zeros(numel(fixtures),2);square=false;non_square=false;
    ids=cell(numel(fixtures),1);writer='';schema='';import_version='';mapping='';evidence_source='';
    for k=1:numel(fixtures)
        item=dsap_orientation_fixture('validate',fixtures{k});a=item.Attestation;c=item.Capture;
        observed=dsap_legacy_observable_profile(c.TIMESlice,c.Provenance);
        if k==1,profile_key=observed.key;header_profile=observed.profile;end
        assert(strcmp(profile_key,observed.key),'DSAP:OrientationProfileMismatch','Reviewed fixtures have different profiles.');
        match=find(strcmp({audit.records.stepId},c.TIMESlice.stepId)&strcmp({audit.records.stackId},c.TIMESlice.stackId));
        assert(numel(match)==1&&strcmp(audit.records(match).key,profile_key), ...
            'DSAP:OrientationProfileAudit','Reviewed fixture is absent from audited profile.');
        kind='IndependentManualDICOMPixelGroundTruth';
        if isfield(a,'HumanAnatomicalReview')&&a.HumanAnatomicalReview,kind='HumanAnatomicalReview';end
        if k==1,writer=a.WriterVersion;schema=a.SchemaVersion;import_version=a.ImportVersion;mapping=a.ApprovedMapping;evidence_source=kind;end
        assert(strcmp(kind,evidence_source),'DSAP:OrientationVersion','Do not mix evidence definitions within one contract.');
        assert(strcmp(mapping,a.ApprovedMapping),'DSAP:OrientationMappingConflict', ...
            'Human-approved mappings differ; stop and investigate writer/schema/source.');
        assert(strcmp(writer,a.WriterVersion)&&strcmp(schema,a.SchemaVersion)&& ...
            strcmp(import_version,a.ImportVersion)&&strcmp(mapping,a.ApprovedMapping), ...
            'DSAP:OrientationVersion','A contract covers one exact writer/schema/import/mapping combination.');
        ids{k}=[c.TIMESlice.stackId '/' c.TIMESlice.roiId '/' c.TIMESlice.stepId];
        square=square||isequal(item.ImageSize,[1024 1024]);
        non_square=non_square||item.ImageSize(1)~=item.ImageSize(2);positions(k,:)=item.CentroidNormalized;
        evidence{k}=struct('FixtureFile',item.FixtureFile,'SourceDICOM',c.SourceDICOM, ...
            'DICOMIdentity',c.DICOMIdentity,'StackId',c.TIMESlice.stackId,'ROIId',c.TIMESlice.roiId, ...
            'StepId',c.TIMESlice.stepId,'NIfTI',c.NIfTI,'ExpectedFile',item.ExpectedFile, ...
            'CaptureSignature',item.CaptureSignature,'ReviewSignature',item.ReviewSignature, ...
            'ExpectedPixelIndicesSignature',dsap_analysis_signature(item.ExpectedPixelIndices), ...
            'PixelCount',numel(item.ExpectedPixelIndices),'ImageSize',item.ImageSize, ...
            'CentroidNormalized',item.CentroidNormalized,'Attestation',a,'Comparison',item.Comparison);
    end
    assert(numel(unique(ids))==numel(ids)&&square&&non_square, ...
        'DSAP:OrientationCoverage','Need distinct real ROIs, a 1024x1024 case and a non-square case.');
    separated=false;
    for i=1:size(positions,1)-2
        for j=i+1:size(positions,1)-1
            for k=j+1:size(positions,1)
                p=positions([i j k],:);
                if min([norm(p(1,:)-p(2,:)),norm(p(1,:)-p(3,:)),norm(p(2,:)-p(3,:))])>=.10,separated=true;end
            end
        end
    end
    assert(separated,'DSAP:OrientationCoverage','Need three visibly distinct positions (normalized centroid distances >=0.10).');
    assert(strcmp(schema,['realm-sha256:' audit.SchemaSHA])&&strcmp(mapping,'transpose'), ...
        'DSAP:OrientationProfileMismatch','Only the reviewed schema and exact transpose are approved.');
    profile=struct('ID',['legacy-observable-v1-' profile_key],'RealmSchemaSHA',audit.SchemaSHA, ...
        'ImportVersion',import_version,'ImportCodeSHA',dsap_orientation_import_signature(), ...
        'NIfTIHeaderProfile',header_profile,'HeaderProfileSHA',profile_key, ...
        'GeometryConvention','raw dimensions = [DICOM Columns, DICOM Rows, 1]; exact transpose', ...
        'SourceLinkConvention','strict ROI.step / Stack / Serial / Study; Study/Stack/rois/Step.nii.gz', ...
        'MaskDomainRules','finite 2D mask; no resize; no interpolation; native column-major indices', ...
        'OrientationMapping',mapping,'ValidationEvidence',{evidence},'AuditIdentity',dsap_source_identity(audit_file));
    orientation=struct('Mapping',mapping,'Source',evidence_source, ...
        'Version',char(version),'ValidationEvidence',{evidence});
    contract=struct('ContractSchemaVersion',3,'Verified',true,'WriterVersion',struct('Known',~isempty(writer),'Value',writer), ...
        'SchemaVersion',schema,'ImportVersion',import_version,'Orientation',orientation, ...
        'LegacyFormatProfile',profile,'HumanAnatomicalReview',strcmp(evidence_source,'HumanAnatomicalReview'), ...
        'Simulation',false,'ApprovedMapping',mapping,'CoverageEligibleFixtures',numel(fixtures), ...
        'HumanReviewBundle',fileparts(fileparts(fixtures{1})), ...
        'ImportCodeSignature',dsap_orientation_import_signature(),'Signature','');
    contract.Signature=dsap_analysis_signature(rmfield(contract,'Signature'));
end
