function mapping=dsap_validate_orientation_contract(contract,provenance,observed,image_size)
% Fail closed on raw observable applicability before any mask transform.
    assert(isstruct(contract)&&isfield(contract,'Signature')&&isfield(contract,'LegacyFormatProfile')&& ...
        contract.ContractSchemaVersion==3&&isequal(contract.Verified,true)&& ...
        strcmp(contract.Signature,dsap_analysis_signature(rmfield(contract,'Signature'))), ...
        'DSAP:OrientationEvidenceMissing','Verified observable-profile contract required.');
    assert(nargin==4&&~isempty(observed),'DSAP:OrientationProfile','Raw header observations required.');
    p=contract.LegacyFormatProfile;o=contract.Orientation;
    assert(strcmp(provenance.SchemaVersion,contract.SchemaVersion)&& ...
        strcmp(contract.ImportVersion,'DSAP-orientation-v2')&& ...
        strcmp(contract.ImportCodeSignature,dsap_orientation_import_signature()), ...
        'DSAP:OrientationVersion','Schema or import implementation is not approved.');
    assert(strcmp(o.Mapping,'transpose')&&numel(o.ValidationEvidence)>=3, ...
        'DSAP:OrientationEvidenceMissing','Real coverage evidence missing.');
    for k=1:numel(observed)
        h=observed(k);
        assert(strcmp(h.key,p.HeaderProfileSHA)&&strcmp(h.RealmSchemaSHA,p.RealmSchemaSHA), ...
            'DSAP:OrientationProfileMismatch','Unknown observable profile: manual review required.');
        d=double(h.header.dimensions(:)');
        assert(isequal(d(1:2),double(image_size([2 1])))&&all(d(3:end)==1), ...
            'DSAP:LegacyMaskInvalid','Raw mask dimensions violate approved DICOM-domain contract.');
    end
    for k=1:numel(o.ValidationEvidence)
        e=o.ValidationEvidence{k};
        assert(e.Comparison.Passed&&strcmp(e.Attestation.ApprovedMapping,o.Mapping), ...
            'DSAP:OrientationEvidenceMissing','Unsuccessful review cannot authorize import.');
    end
    mapping=o.Mapping;
end
