function [mask,capillary,model,features,full_field] = segment_large_vessels_cave(source_file,aif,brain,scope,limits,polarity,varargin)
% Same official AV union approved in the independent trial. No DCA filtering.
    p=inputParser;
    p.addParameter('ShowProgress',true,@(x)islogical(x)&&isscalar(x));
    p.addParameter('Prepared',[],@(x)isempty(x)||isstruct(x));
    p.parse(varargin{:});
    shape=size(aif);band=dsap_validate_cranial_limits(limits,shape);
    assert(isequal(size(brain),shape)&&isequal(size(scope),shape),'CAVE 掩膜尺寸不一致。');
    scope=logical(scope)&band;
    prepared=p.Results.Prepared;
    if isempty(prepared)
        [full_field,job]=dsap_cave_full_field(source_file,shape,polarity,p.Results.ShowProgress);
    else
        assert(isfield(prepared,'FullField')&&~isempty(prepared.FullField),'DSAP:PreparationUnavailable','血管准备未完成：%s',prepared.Reason);
        identity=dsap_source_identity(source_file);
        full_field=prepared.FullField;job=prepared.WorkerJob;
        assert(strcmp(identity.SHA256,prepared.SourceIdentity.SHA256)&&strcmp(full_field.Provenance.source_sha256,identity.SHA256), ...
            'DSAP:PreparationSource','准备结果不属于当前 DSA。');
        assert(strcmp(polarity,'dark')&&full_field.Provenance.complete&& ...
            isequal(size(full_field.ArteryMask),shape)&&isequal(size(full_field.VeinMask),shape), ...
            'DSAP:PreparationShape','准备结果的输入类型或尺寸无效。');
    end
    provenance=full_field.Provenance;raw=full_field.UnionMask;
    mask=raw&scope;capillary=logical(brain)&scope&~mask&~aif;
    model=struct('Method','CAVE-AV-union','Threshold',0.5,'Sensitivity',0, ...
        'CacheHit',provenance.cache_hit,'Provenance',provenance,'WorkerJob',job, ...
        'ManualVerticalConstraint',true,'SignalValidPixelCount',nnz(brain), ...
        'FullFieldRawDetectionPixelCount',nnz(raw),'ExcludedPixelCount',nnz(mask), ...
        'ExcludedPixelFraction',nnz(mask)/max(nnz(scope),1),'ManuallyCorrected',false, ...
        'ShortLineRemoval',struct('Enabled',false), ...
        'ManualCorrectionOperation','automatic AV union; optional manual additions and restorations', ...
        'Warning','Includes small vessels; user must review before excluding from tissue perfusion');
    features=struct('RawVesselMask',raw,'AutomaticVesselMask',mask, ...
        'ArteryMask',full_field.ArteryMask&scope,'VeinMask',full_field.VeinMask&scope, ...
        'ManualAddedMask',false(shape),'ManualRestoredMask',false(shape));
end
